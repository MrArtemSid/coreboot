void program_hsio_sata_wbg_b0(void)
{
	if (pci_read_config32(PCH_SATA_DEV, PCI_VENDOR_ID) == 0xffffffff)
		return;

	printk(BIOS_DEBUG, "Wellsburg SATA HSIO: lane owner %02x\n",
	       pci_read_config8(PCH_PCIE_DEV(0), 0x410));

	/* Apply the PHY recipe before enabling any SATA ports. */
	pci_update_config32(PCH_SATA_DEV, SATA_SCLKG, ~0x1ff, 0x183);
	pci_or_config16(PCH_SATA_DEV, SATA_PCS, BIT(15));

	for (size_t i = 0; i < ARRAY_SIZE(hsio_sata_wbg_b0); i++)
		hsio_update_row(hsio_sata_wbg_b0[i]);
	for (size_t i = 0; i < ARRAY_SIZE(hsio_sata_shared_wbg_b0); i++)
		hsio_sata_shared_update_row(hsio_sata_shared_wbg_b0[i]);
	for (size_t i = 0; i < ARRAY_SIZE(hsio_sata_dt_wbg_b0); i++)
		hsio_update_row(hsio_sata_dt_wbg_b0[i]);
	for (size_t i = 0; i < ARRAY_SIZE(hsio_sata_shared_dt_wbg_b0); i++)
		hsio_sata_shared_update_row(hsio_sata_shared_dt_wbg_b0[i]);
}
