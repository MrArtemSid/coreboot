/*
 * Super I/O init table taken verbatim from the stock AMI NCT5532DPeiInit
 * PEIM (D4M4-orig.bin, table at 0xffdcd6ac, 55 entries).
 * Entry: { io port, and-mask, or-value }. and-mask == 0 -> plain write,
 * otherwise read-modify-write of the same port (as the stock loop does).
 * Effect: multi-function pin setup (CR1a/1b/1d/2a/2c/2f/3e),
 * KBC (LDN5) at 0x60/0x64 IRQ1 + CRf0=0x83, CIR (LDN6) disabled.
 */
static const struct {
	u16 port;
	u8 and_mask;
	u8 or_val;
} ami_sio_table[] = {
	{0x2e, 0x00, 0x87}, {0x2e, 0x00, 0x87}, {0x2e, 0x00, 0x2f}, {0x2f, 0xbd, 0x00},
	{0x2e, 0x00, 0x1a}, {0x2f, 0x3f, 0x00}, {0x2e, 0x00, 0x1b}, {0x2f, 0xef, 0x10},
	{0x2e, 0x00, 0x2a}, {0x2f, 0xe4, 0x08}, {0x2e, 0xff, 0x1c}, {0x2f, 0xe7, 0x08},
	{0x2e, 0x00, 0x1d}, {0x2f, 0xfe, 0x00}, {0x2e, 0x00, 0x2a}, {0x2f, 0x3c, 0x00},
	{0x2e, 0x00, 0x2c}, {0x2f, 0x86, 0x00}, {0x2e, 0x00, 0x2f}, {0x2f, 0x00, 0x00},
	{0x2e, 0x00, 0x07}, {0x2f, 0x00, 0x05}, {0x2e, 0x00, 0x60}, {0x2f, 0x00, 0x00},
	{0x2e, 0x00, 0x61}, {0x2f, 0x00, 0x60}, {0x2e, 0x00, 0x62}, {0x2f, 0x00, 0x00},
	{0x2e, 0x00, 0x63}, {0x2f, 0x00, 0x64}, {0x2e, 0x00, 0x70}, {0x2f, 0x00, 0x01},
	{0x2e, 0x00, 0x30}, {0x2f, 0x00, 0x01}, {0x2e, 0x00, 0x07}, {0x2f, 0x00, 0x05},
	{0x2e, 0x00, 0xf0}, {0x2f, 0x00, 0x83}, {0x2e, 0x00, 0x07}, {0x2f, 0x00, 0x06},
	{0x2e, 0x00, 0x60}, {0x2f, 0x00, 0x00}, {0x2e, 0x00, 0x61}, {0x2f, 0x00, 0x00},
	{0x2e, 0x00, 0x62}, {0x2f, 0x00, 0x00}, {0x2e, 0x00, 0x63}, {0x2f, 0x00, 0x00},
	{0x2e, 0x00, 0x70}, {0x2f, 0x00, 0x00}, {0x2e, 0x00, 0x07}, {0x2f, 0x00, 0x06},
	{0x2e, 0x00, 0x30}, {0x2f, 0x00, 0x00}, {0x2e, 0x00, 0xaa},
};

void mainboard_config_superio(void)
{
	const pnp_devfn_t serial_dev = PNP_DEV(0x2e, NCT5539D_SP1);

	for (size_t i = 0; i < ARRAY_SIZE(ami_sio_table); i++) {
		u8 val = ami_sio_table[i].or_val;

		if (ami_sio_table[i].and_mask)
			val |= inb(ami_sio_table[i].port) & ami_sio_table[i].and_mask;
		outb(val, ami_sio_table[i].port);
	}

	/* Not done by stock PEI; harmless if COM A is not wired. */
	nuvoton_enable_serial(serial_dev, CONFIG_TTYS0_BASE);
}

void bootblock_mainboard_init(void)
{
	numlock_beacon_stage(BEACON_BOOTBLOCK);
}
